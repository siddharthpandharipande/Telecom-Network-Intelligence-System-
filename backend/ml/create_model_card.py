"""Generate backend/models/model_card.json for Phase 7."""
import json
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.cluster import DBSCAN
from sklearn.preprocessing import StandardScaler

repo_root = Path(__file__).resolve().parent.parent.parent
models_dir = repo_root / "backend" / "models"
df = pd.read_csv(repo_root / "dataset" / "nexusnet_features_labeled.csv")

with open(repo_root / "backend" / "ml" / "config.json", "r", encoding="utf-8") as f:
    config = json.load(f)

# Ablation rows
ablation_df = pd.read_csv(models_dir / "ablation_results.csv")
ablation_rows = ablation_df.to_dict(orient="records")

# Medians
base_telemetry = config["telemetry_columns"]
medians = {col: round(float(df[col].median()), 4) for col in base_telemetry}

# DBSCAN sweep table
X = df[base_telemetry].values
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

sweep_results = []
for eps_val in np.arange(0.3, 2.6, 0.1):
    eps_rounded = round(float(eps_val), 2)
    db = DBSCAN(eps=eps_rounded, min_samples=16).fit(X_scaled)
    labels = db.labels_
    n_clusters = len(set(labels)) - (1 if -1 in labels else 0)
    n_noise = int(np.sum(labels == -1))
    noise_pct = round((n_noise / len(labels)) * 100, 2)
    sweep_results.append(
        {
            "eps": eps_rounded,
            "min_samples": 16,
            "n_clusters": n_clusters,
            "n_noise": n_noise,
            "noise_pct": noise_pct,
        }
    )

model_card = {
    "model_version": "2.0.0-2026-10-14",
    "dataset": {
        "rows": 6000,
        "date_range": f"{df['Timestamp'].min()} to {df['Timestamp'].max()}",
        "synthetic": True,
        "note": "synthetic, single day, generator unavailable",
    },
    "label": {
        "name": "Legacy5",
        "description": "Legacy 5-clause operational threshold policy",
        "clauses": config["label"]["clauses"],
        "prevalence": {
            "Normal": int(np.sum(df["Label_Legacy5"] == 0)),
            "At_Risk": int(np.sum(df["Label_Legacy5"] == 1)),
            "Normal_pct": round(float(np.mean(df["Label_Legacy5"] == 0) * 100), 2),
            "At_Risk_pct": round(float(np.mean(df["Label_Legacy5"] == 1) * 100), 2),
        },
    },
    "decision": {
        "shipped_variant": "legacy_policy",
        "reason": (
            "Phase 3 ablation revealed (QoS3, F_cause) achieved CV ROC-AUC of 0.578 "
            "(below the >= 0.70 threshold for cause-side failure forecasting). "
            "Per decision rule, shipping variant 'legacy_policy' (label Legacy5, features F9_current). "
            "Risk score approximates a rule-defined SLA policy; metrics reflect that the label "
            "is a function of the inputs and must not be read as failure-prediction accuracy."
        ),
    },
    "svm": {
        "features": config["svm_features"]["numeric"],
        "best_params": {
            "C": 10,
            "class_weight": "balanced",
            "gamma": 0.1,
            "kernel": "rbf",
        },
        "cv_metrics": {
            "best_cv_f1": 0.9577,
        },
        "test_metrics": {
            "accuracy": 0.9642,
            "precision": 0.9494,
            "recall": 0.9749,
            "f1": 0.9620,
            "roc_auc": 0.9955,
            "pr_auc": 0.9950,
            "brier_score": 0.0265,
        },
        "confusion_matrix": {
            "tn": 613,
            "fp": 29,
            "fn": 14,
            "tp": 544,
            "matrix": [[613, 29], [14, 544]],
        },
    },
    "ablation": ablation_rows,
    "dbscan": {
        "features": config["dbscan"]["features"],
        "eps": 1.6,
        "min_samples": 16,
        "n_clusters": 2,
        "noise_count": 244,
        "noise_pct": 4.07,
        "sweep_table": sweep_results,
    },
    "risk_anomaly_matrix": {
        "normal_inlier": 3127,
        "normal_anomaly": 44,
        "at_risk_inlier": 2629,
        "at_risk_anomaly": 200,
        "total": 6000,
    },
    "training_medians": medians,
    "limitations": [
        "synthetic data: Entire dataset of 6,000 records was synthetically generated; original data generation script is lost.",
        "single snapshot per asset: Telemetry covers only 24 hours (2026-09-16 00:00 to 23:00) with exactly one record per asset, containing no time-series history or recurring behavior.",
        "label is rule-derived: Labels are generated by deterministic threshold rules over input telemetry; metrics reflect policy rule replication rather than independent empirical failure prediction.",
        "scores are not failure probabilities: Model risk score reflects adherence to the composite SLA policy boundary, not true failure likelihood.",
        "timestamps assumed local: Local asset time is assumed when computing peak hours (18:00-22:00) without timezone localization or regional offset adjustment.",
    ],
}

out_path = models_dir / "model_card.json"
with open(out_path, "w", encoding="utf-8") as f:
    json.dump(model_card, f, indent=2)

print(f"Model card written to: {out_path}")
