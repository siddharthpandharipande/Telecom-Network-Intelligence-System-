def seed_world_assets():
    db = SessionLocal()
    now = datetime(2026, 9, 16, 12, 0, 0)
    count_new = 0

    for item in WORLD_SEED_ASSETS:
        aid = item["asset_id"]
        existing = db.query(Asset).filter(Asset.asset_id == aid).first()
        if not existing:
            asset = Asset(
                asset_id=aid,
                asset_type=item["asset_type"],
                continent=item["continent"],
                country=item["country"],
                city=item["city"],
                region=item["region"],
                latitude=item["latitude"],
                longitude=item["longitude"],
                created_at=now,
                updated_at=now,
            )
            db.add(asset)
            db.flush()

            reading = Reading(
                asset_id=aid,
                timestamp=now,
                signal_strength_dbm=item["signal_strength_dbm"],
                latency_ms=item["latency_ms"],
                packet_loss_pct=item["packet_loss_pct"],
                throughput_mbps=180.0,
                connected_users=450,
                traffic_load_pct=item["traffic_load_pct"],
                call_drop_rate_pct=0.3,
                resource_utilization_pct=42.0,
                peak_hour=False,
                network_stress_index=35.0,
                signal_quality_score=85.0,
                throughput_per_user=0.4,
                risk_label="Normal",
                risk_score=0.12,
                is_at_risk=False,
                dbscan_cluster=1,
                is_anomaly=False,
                nearest_core_distance=0.8,
                status=item["status"],
                model_version="2.0.0-2026-10-14",
                source="seed",
            )
            db.add(reading)
            db.flush()

            asset.latest_reading_id = reading.id
            count_new += 1

    db.commit()
    db.close()
    print(f"Successfully seeded {count_new} world assets and neighboring routers.")


if __name__ == "__main__":
    seed_world_assets()
